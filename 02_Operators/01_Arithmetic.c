#include<stdio.h>

int main(){
    int a = 10 ,b = 3 ;
    printf("Arithmetic Operators in C\n");
    printf("The value of a + b is %d\n ", a+b );
    printf("The value of a - b is %d\n ", a-b );
    printf("The value of a * b is %d\n ", a*b );
    printf("The value of a / b is %d\n ", a/b );
    printf("The value of a %% b is %d\n ", a%b );
   
    return 0;

}